#!/usr/bin/env node
/**
 * gen-api-matrix.js — extract the Lua-facing API surface from Psych Engine
 * FunkinLua.hx files and print a comparison matrix as Markdown.
 *
 *   node tools/gen-api-matrix.js "path/to/FunkinLua.hx|label" ["...|label"] > api-matrix.md
 *
 * The optional "|label" suffix keeps local paths out of the generated doc.
 * Read-only: never touches the source files.
 */
const fs = require("fs");
const path = require("path");

const CALLBACK = /add_callback\s*\(\s*lua\s*,\s*['"]([A-Za-z0-9_]+)['"]/g;

function parseArg(arg) {
  const i = arg.indexOf("|");
  if (i < 0) return { file: arg, label: path.basename(path.dirname(arg)) || arg };
  return { file: arg.slice(0, i), label: arg.slice(i + 1) };
}

function collect(file) {
  const src = fs.readFileSync(file, "utf8");
  const names = new Set();
  let m;
  while ((m = CALLBACK.exec(src)) !== null) names.add(m[1]);
  return names;
}

const args = process.argv.slice(2);
if (args.length === 0) {
  console.error("usage: node tools/gen-api-matrix.js <FunkinLua.hx[|label]> [...]");
  process.exit(1);
}

const sets = args.map((a) => {
  const { file, label } = parseArg(a);
  return { label, names: collect(file) };
});

const all = new Set();
for (const s of sets) for (const n of s.names) all.add(n);
const sorted = [...all].sort((a, b) => a.localeCompare(b));

const fence = "```";
const out = [];
out.push("# API matrix (generated)");
out.push("");
const bt = String.fromCharCode(96);
out.push("Generated by " + bt + "tools/gen-api-matrix.js" + bt + " — do not edit by hand.");
out.push("Regenerate with:");
out.push("");
out.push(fence + "powershell");
out.push('node tools/gen-api-matrix.js "<FunkinLua.hx>|psych-0.6.3-fork" "<FunkinLua.hx>|psych-1.0-sample" > api-matrix.md');
out.push(fence);
out.push("");
out.push("| source | unique registrations |");
out.push("|---|---|");
for (const s of sets) out.push("| " + s.label + " | " + s.names.size + " |");
out.push("| **union** | **" + all.size + "** |");
out.push("");
out.push("| # | function | " + sets.map((s) => s.label).join(" | ") + " |");
out.push("|---|---|" + sets.map(() => "---").join("|") + "|");
sorted.forEach((n, i) => {
  out.push("| " + (i + 1) + " | " + n + " | " + sets.map((s) => (s.names.has(n) ? "yes" : "—")).join(" | ") + " |");
});
out.push("");
console.log(out.join("\n"));
